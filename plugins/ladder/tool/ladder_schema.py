"""Schema references: Ladder English points at a database schema that lives elsewhere (an EF Core
model snapshot, or a JSON export of a database), instead of describing it.

In ladder.json:
  "schemas": {"qbs": {"kind": "efcore-snapshot", "source": "../../qb_api_models/Migrations/QbsDbContextModelSnapshot.cs"},
              "reports": {"kind": "json", "source": "schemas/reports.json"}}

In the English:
  reads: Employee, Division          writes: qbs:Employee
  > employees whose [[Employee.TerminatedOn]] is empty, ordered by [[Employee.LastName]]

A reference names an entity (its class name or its table name) and optionally a property or
navigation; a prefix (`qbs:`) picks the schema when the name exists in more than one.
"""
from __future__ import annotations

import difflib
import hashlib
import json
import re
from dataclasses import dataclass, field
from pathlib import Path

REF_RE = re.compile(r"\[\[\s*(?:([A-Za-z_]\w*)\s*:)?\s*([A-Za-z_][\w]*)(?:\.([A-Za-z_]\w*))?\s*\]\]")
ENTITY_REF_RE = re.compile(r"^\s*(?:([A-Za-z_]\w*)\s*:)?\s*([A-Za-z_]\w*)\s*$")


@dataclass
class Prop:
    name: str
    clr: str = ""
    column: str = ""
    column_type: str = ""
    required: bool = False
    max_length: int | None = None
    generated: bool = False

    def fact(self) -> str:
        bits = [f"column {self.column}"]
        if self.column_type:
            bits.append(self.column_type)
        elif self.clr:
            bits.append(self.clr)
        bits.append("required" if self.required else "optional")
        if self.max_length:
            bits.append(f"max {self.max_length}")
        if self.generated:
            bits.append("generated by the database")
        return ", ".join(bits)


@dataclass
class Nav:
    name: str
    target: str
    many: bool
    foreign_key: str = ""
    through: str = ""

    def fact(self) -> str:
        s = f"{'many' if self.many else 'one'} {self.target}"
        if self.through:
            s += f" through {self.through}"
        if self.foreign_key:
            s += f" via {self.foreign_key}"
        return s


@dataclass
class Entity:
    name: str            # class name without namespace
    full_name: str
    table: str = ""
    db_schema: str = ""
    keys: list[str] = field(default_factory=list)
    props: dict[str, Prop] = field(default_factory=dict)
    navs: dict[str, Nav] = field(default_factory=dict)
    indexes: list[str] = field(default_factory=list)

    def table_name(self) -> str:
        return f"{self.db_schema}.{self.table}" if self.db_schema else self.table

    def fact(self) -> str:
        return f"table {self.table_name()}, key {', '.join(self.keys) or '(none)'}"

    def describe(self) -> str:
        """The table form shown to people and to the generator."""
        lines = [f"entity {self.name}    table {self.table_name()}    key {', '.join(self.keys) or '-'}"]
        for p in self.props.values():
            lines.append(f"  {p.name:<24} {p.fact()}")
        for n in self.navs.values():
            lines.append(f"  {n.name:<24} -> {n.fact()}")
        for ix in self.indexes:
            lines.append(f"  index {ix}")
        return "\n".join(lines)


# ---------------------------------------------------------------- readers

def _blocks(text: str, opener: re.Pattern) -> list[tuple[re.Match, str]]:
    """(match, body) for each `opener ... {body}` block, with brace matching."""
    out = []
    for m in opener.finditer(text):
        i = text.find("{", m.end())
        if i < 0:
            continue
        depth, j = 0, i
        while j < len(text):
            if text[j] == "{":
                depth += 1
            elif text[j] == "}":
                depth -= 1
                if depth == 0:
                    break
            j += 1
        out.append((m, text[i + 1:j]))
    return out


def _statements(body: str) -> list[str]:
    """Split a lambda body into statements at top-level semicolons."""
    out, depth, cur = [], 0, []
    for ch in body:
        if ch in "({":
            depth += 1
        elif ch in ")}":
            depth -= 1
        if ch == ";" and depth == 0:
            out.append("".join(cur).strip())
            cur = []
        else:
            cur.append(ch)
    if "".join(cur).strip():
        out.append("".join(cur).strip())
    return out


def read_efcore_snapshot(path: Path) -> dict[str, Entity]:
    """Entities from an EF Core model snapshot (Migrations/<Context>ModelSnapshot.cs)."""
    text = path.read_text(encoding="utf-8-sig")
    ents: dict[str, Entity] = {}
    opener = re.compile(r'modelBuilder\.Entity\(\s*"([^"]+)"\s*,\s*(\w+)\s*=>')
    for m, body in _blocks(text, opener):
        full = m.group(1)
        short = full.split(".")[-1]
        e = ents.setdefault(short, Entity(name=short, full_name=full))
        for st in _statements(body):
            st1 = " ".join(st.split())
            if pm := re.match(r'\w+\.Property<([^>]+)>\("([^"]+)"\)(.*)', st1):
                clr, name, rest = pm.groups()
                p = e.props.setdefault(name, Prop(name=name))
                p.clr = clr
                p.column = (re.search(r'HasColumnName\("([^"]+)"\)', rest) or [None, name])[1]
                ct = re.search(r'HasColumnType\("([^"]+)"\)', rest)
                p.column_type = ct.group(1) if ct else ""
                ml = re.search(r"HasMaxLength\((\d+)\)", rest)
                p.max_length = int(ml.group(1)) if ml else None
                # value types are required unless nullable; reference types only with IsRequired()
                value_type = clr.rstrip("?") in ("int", "long", "short", "byte", "bool", "decimal", "double",
                                                 "float", "DateTime", "DateTimeOffset", "Guid", "TimeSpan",
                                                 "DateOnly", "TimeOnly")
                p.required = "IsRequired()" in rest or (value_type and not clr.endswith("?"))
                p.generated = "ValueGeneratedOnAdd()" in rest
            elif km := re.match(r'\w+\.HasKey\((.*)\)', st1):
                e.keys = re.findall(r'"([^"]+)"', km.group(1))
            elif tm := re.match(r'\w+\.ToTable\(\s*"([^"]+)"(?:\s*,\s*"([^"]+)")?', st1):
                e.table, e.db_schema = tm.group(1), tm.group(2) or ""
            elif im := re.match(r'\w+\.HasIndex\((.*?)\)(.*)', st1):
                cols = ", ".join(re.findall(r'"([^"]+)"', im.group(1)))
                e.indexes.append(cols + (" (unique)" if "IsUnique()" in im.group(2) else ""))
            elif nm := re.match(r'\w+\.Has(One|Many)\(\s*"([^"]+)"\s*,\s*"([^"]+)"\s*\)(.*)', st1):
                kind, target, nav, rest = nm.groups()
                fk = re.search(r'HasForeignKey\(([^)]*)\)', rest)
                through = re.search(r'UsingEntity\(\s*"([^"]+)"', rest)
                many = kind == "Many"
                e.navs[nav] = Nav(name=nav, target=target.split(".")[-1], many=many,
                                  foreign_key=", ".join(re.findall(r'"([^"]+)"', fk.group(1))) if fk else "",
                                  through=through.group(1).split(".")[-1] if through else "")
                # the other side, when it is named: WithMany("Employees") / WithOne("Division")
                inv = re.search(r'With(One|Many)\(\s*"([^"]+)"\s*\)', rest)
                if inv:
                    other = ents.setdefault(target.split(".")[-1], Entity(name=target.split(".")[-1], full_name=target))
                    other.navs.setdefault(inv.group(2), Nav(name=inv.group(2), target=short,
                                                            many=inv.group(1) == "Many",
                                                            through=e.navs[nav].through))
    for e in ents.values():
        if not e.table:
            e.table = e.name
    return ents


def read_json_schema(path: Path) -> dict[str, Entity]:
    """Entities from a JSON export, for databases without migrations:
    {"entities": [{"name": "ShiftSummary", "table": "dbo.shift_summary", "keys": ["Id"],
                   "properties": [{"name": "Id", "column": "id", "type": "int", "required": true}],
                   "navigations": [{"name": "Site", "target": "Site", "many": false, "foreignKey": "SiteId"}]}]}"""
    data = json.loads(path.read_text())
    ents = {}
    for d in data.get("entities", []):
        schema, _, table = d.get("table", d["name"]).rpartition(".")
        e = Entity(name=d["name"], full_name=d["name"], table=table, db_schema=schema, keys=d.get("keys", []))
        for p in d.get("properties", []):
            e.props[p["name"]] = Prop(name=p["name"], column=p.get("column", p["name"]),
                                      column_type=p.get("type", ""), required=bool(p.get("required")),
                                      max_length=p.get("maxLength"), generated=bool(p.get("generated")))
        for n in d.get("navigations", []):
            e.navs[n["name"]] = Nav(name=n["name"], target=n["target"], many=bool(n.get("many")),
                                    foreign_key=n.get("foreignKey", ""), through=n.get("through", ""))
        ents[e.name] = e
    return ents


READERS = {"efcore-snapshot": read_efcore_snapshot, "json": read_json_schema}


def load_schemas(cfg: dict, root: Path) -> dict[str, dict[str, Entity]]:
    out = {}
    for name, s in (cfg.get("schemas") or {}).items():
        reader = READERS.get(s.get("kind", ""))
        if reader is None:
            raise SystemExit(f"schema '{name}': unknown kind '{s.get('kind')}' (use {', '.join(READERS)})")
        path = root / s["source"]
        if not path.exists():
            raise SystemExit(f"schema '{name}': source not found: {path}")
        out[name] = reader(path)
    return out


def load_schemas_at(cfg: dict, root: Path, ref: str) -> dict[str, dict[str, Entity]]:
    """The project's schemas as they were at a git ref (for `ladder check --schema-since REF`)."""
    import subprocess, tempfile
    out = {}
    for name, s in (cfg.get("schemas") or {}).items():
        path = (root / s["source"]).resolve()
        top = subprocess.run(["git", "-C", str(path.parent), "rev-parse", "--show-toplevel"],
                             capture_output=True, text=True)
        if top.returncode != 0:
            raise SystemExit(f"schema '{name}': {path} is not in a git repository, so --schema-since can't read it")
        rel = path.relative_to(Path(top.stdout.strip()).resolve()).as_posix()
        old = subprocess.run(["git", "-C", top.stdout.strip(), "show", f"{ref}:{rel}"], capture_output=True)
        if old.returncode != 0:
            print(f"note: schema '{name}' did not exist at {ref} ({rel}); every reference to it counts as new")
            out[name] = {}
            continue
        with tempfile.NamedTemporaryFile(suffix=path.suffix, delete=False) as f:
            f.write(old.stdout)
        try:
            out[name] = READERS[s["kind"]](Path(f.name))
        finally:
            Path(f.name).unlink()
    return out


# ---------------------------------------------------------------- references

@dataclass
class Ref:
    text: str                  # as written
    schema: str | None         # prefix, if written
    entity: str
    member: str | None
    kind: str                  # "reads", "writes" or "mention"


def step_refs(n) -> list[Ref]:
    """Every schema reference a step makes: its reads:/writes: lines and [[...]] in its text."""
    refs = []
    for kind in ("reads", "writes"):
        for item in getattr(n, kind, []):
            k = kind
            q = re.match(r"^(.*?)\s*\((updates? only|updates?)\)\s*$", item.strip(), re.I)
            if q and kind == "writes":
                item, k = q.group(1), "updates"      # writes: X (updates only): never inserts rows
            m = ENTITY_REF_RE.match(item)
            if m:
                refs.append(Ref(item.strip(), m.group(1), m.group(2), None, k))
    text = "\n".join([n.title, n.inputs, n.outputs, n.effects, *n.steps, *n.notes])
    for m in REF_RE.finditer(text):
        refs.append(Ref(m.group(0), m.group(1), m.group(2), m.group(3), "mention"))
    return refs


def resolve(ref: Ref, schemas: dict[str, dict[str, Entity]]):
    """(schema name, entity, member or None, problem or None)."""
    pools = {ref.schema: schemas.get(ref.schema, {})} if ref.schema else schemas
    if ref.schema and ref.schema not in schemas:
        return None, None, None, f"{ref.text}: no schema named '{ref.schema}' (ladder.json has {', '.join(schemas) or 'none'})"
    hits = []
    for sname, ents in pools.items():
        for e in ents.values():
            if ref.entity in (e.name, e.table, e.table_name()):
                hits.append((sname, e))
    if not hits:
        names = sorted({e.name for ents in pools.values() for e in ents.values()})
        close = difflib.get_close_matches(ref.entity, names, n=3)
        return None, None, None, f"{ref.text}: no entity '{ref.entity}'" + (f" (did you mean {', '.join(close)}?)" if close else "")
    if len({s for s, _ in hits}) > 1:
        return None, None, None, (f"{ref.text}: '{ref.entity}' exists in {', '.join(sorted({s for s, _ in hits}))}; "
                                  f"add the schema name: {hits[0][0]}:{ref.entity}" + (f" (in text, [[{hits[0][0]}:{ref.entity}.{ref.member}]])" if ref.member else ""))
    sname, e = hits[0]
    if ref.member is None:
        return sname, e, None, None
    member = e.props.get(ref.member) or e.navs.get(ref.member)
    if member is None:
        names = list(e.props) + list(e.navs)
        close = difflib.get_close_matches(ref.member, names, n=3)
        low = [x for x in names if x.lower() == ref.member.lower()]
        hint = f" (did you mean {', '.join(low or close)}?)" if (low or close) else ""
        return sname, e, None, f"{ref.text}: {e.name} has no property or navigation '{ref.member}'{hint}"
    return sname, e, member, None


def ref_key(sname: str, e: Entity, member) -> str:
    return f"{sname}:{e.name}" + (f".{member.name}" if member else "")


def ref_fact(e: Entity, member) -> str:
    return member.fact() if member else e.fact()


def check_refs(tree, schemas) -> tuple[list[dict], dict[str, dict[str, str]], list[dict]]:
    """Problems, the facts each step relies on ({step: {ref key: fact}}), and warnings."""
    problems, facts, warnings = [], {}, []
    for n in tree.values():
        refs = step_refs(n)
        if refs and not schemas:
            problems.append(dict(kind="schema-ref", node=n.id,
                                 msg="refers to a schema, but ladder.json lists no \"schemas\""))
            continue
        written = set()
        for r in refs:
            sname, e, member, problem = resolve(r, schemas)
            if problem:
                problems.append(dict(kind="schema-ref", node=n.id, msg=problem))
                continue
            facts.setdefault(n.id, {})[ref_key(sname, e, member)] = ref_fact(e, member)
            if member is None:
                # A whole-entity reference (reads:/writes:) also relies on the members the code may use
                # without naming them: compared so that removed or changed members flag the step, and
                # (for writes) new required columns too, since inserts must now set them.
                star = ref_key(sname, e, None) + (".* (writes)" if r.kind == "writes" else ".*")
                facts[n.id][star] = members_fact(e)
            if r.kind in ("writes", "updates"):
                written.add(sname)
        if len(written) > 1:
            warnings.append(dict(kind="two-databases", node=n.id,
                                 msg=f"writes to {', '.join(sorted(written))}: no single transaction covers both; "
                                     f"say in the English what happens if the second write fails"))
    return problems, facts, warnings


def members_fact(e: Entity) -> str:
    items = [f"{p.name}={p.fact()}" for p in e.props.values()] + [f"{n.name}=-> {n.fact()}" for n in e.navs.values()]
    return " | ".join(sorted(items))


def _members(text: str) -> dict[str, str]:
    return dict(x.split("=", 1) for x in text.split(" | ") if "=" in x)


def fact_changes(key: str, was: str, now: str) -> list[str]:
    """What changed in one recorded fact, in words; [] when nothing that matters changed."""
    if was == now:
        return []
    if key.endswith(".*") or key.endswith(".* (writes)"):
        a, b = _members(was), _members(now)
        ent = key.split(".*")[0]
        out = [f"{ent}.{m} removed (was {a[m]})" for m in a if m not in b]
        out += [f"{ent}.{m}: {a[m]} -> {b[m]}" for m in a if m in b and a[m] != b[m]]
        if key.endswith("(writes)"):
            out += [f"{ent}.{m} added, {b[m]} (inserts must now set it; if this step only updates rows, "
                    f"write `writes: {ent.split(':')[-1]} (updates only)`)" for m in b
                    if m not in a and ", required" in b[m] and "generated by the database" not in b[m]
                    and not b[m].startswith("-> ")]
        return out
    return [f"{key}: {was} -> {now}"]


def facts_hash(facts: dict[str, str]) -> str:
    return hashlib.sha1(json.dumps(facts, sort_keys=True).encode()).hexdigest()[:8]


def prompt_text(n_ids: list[str], tree, schemas) -> str:
    """The schema facts for the entities the given steps refer to, for a generator prompt."""
    if not schemas:
        return ""
    seen: dict[tuple[str, str], Entity] = {}
    for nid in n_ids:
        if nid not in tree:
            continue
        for r in step_refs(tree[nid]):
            sname, e, _, problem = resolve(r, schemas)
            if not problem:
                seen[(sname, e.name)] = e
    if not seen:
        return ""
    parts = ["=== Database schema these steps use (from the EF model; exact. Never rename, re-map or "
             "re-declare these entities or columns: use them as they are):"]
    for (sname, _), e in sorted(seen.items()):
        parts.append(f"[{sname}] " + e.describe())
    return "\n".join(parts) + "\n"
